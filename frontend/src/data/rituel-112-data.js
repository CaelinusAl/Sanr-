// Bugünün ritüeli (rastgele seçim)
export const getBugunRitueli = () => {
  const today = new Date().toDateString();
  const seed = today.split('').reduce((a, c) => a + c.charCodeAt(0), 0);
  const index = seed % mikroRitueller.length;
  return mikroRitueller[index];
};
